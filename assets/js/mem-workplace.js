/**
 * Workplace display: workplace name, large rotating QR code, six-digit PIN, countdown,
 * connection status and logout. Challenges refresh without reloading the page.
 */
(function (window, document) {
	'use strict';

	var MEM = window.MEM, h = MEM.h, CFG = MEM.config;
	var root = document.getElementById('mem-workplace-app');
	if (!root) { return; }

	var current = null;       // Last challenge received.
	var offset = 0;           // Server time - client time (ms).
	var lastOk = 0;           // Timestamp of the last successful fetch.
	var fetching = false, retryTimer = null, wakeLock = null;

	var el = {};

	function build() {
		el.status = h('span', { class: 'mem-wp__status', role: 'status', 'aria-live': 'polite' });
		el.name = h('h1', { class: 'mem-wp__name', text: 'Sede' });
		el.qr = h('div', { class: 'mem-wp__qr', role: 'img', 'aria-label': 'Codice QR presenze' });
		el.pin = h('div', { class: 'mem-wp__pin', 'aria-live': 'off' });
		el.fill = h('div', { class: 'mem-wp__bar-fill', style: 'width:100%' });
		el.secs = h('div', { class: 'mem-wp__secs' });
		el.left = h('div', {}, [
			el.name,
			h('p', { class: 'mem-wp__help', text: 'Per timbrare: accedi al portale dal tuo telefono e scansiona il QR, oppure inserisci il PIN.' }),
			h('div', { class: 'mem-wp__pin-label', text: 'PIN' }),
			el.pin,
			h('div', { class: 'mem-wp__countdown' }, [
				h('div', { class: 'mem-wp__bar-track', role: 'progressbar', 'aria-label': 'Tempo alla rotazione del codice', 'aria-valuemin': 0, 'aria-valuemax': 15 }, el.fill),
				el.secs
			])
		]);
		el.panel = h('div', { class: 'mem-wp__panel' }, [el.left, el.qr]);
		el.unavailable = h('div', { class: 'mem-wp__panel', hidden: true }, h('div', { class: 'mem-wp__unavailable', style: 'grid-column:1/-1' }, [
			MEM.icon('wifi-off'),
			h('h1', { class: 'mem-wp__name', text: 'Codici non disponibili' }),
			h('p', { class: 'mem-wp__help', text: 'Impossibile ottenere codici aggiornati dal server. Nuovo tentativo in corso… Se il problema persiste, controlla la connessione di questo dispositivo.' })
		]));
		MEM.render(root, [
			h('header', { class: 'mem-wp__bar' }, [
				h('div', { class: 'mem-brand' }, [
					CFG.logo ? h('img', { class: 'mem-brand__logo', src: CFG.logo, alt: 'Dolly' }) : h('span', { class: 'mem-brand__wordmark', text: 'Dolly' }),
					h('span', { class: 'mem-brand__sub', text: 'Codice presenze' })
				]),
				h('div', { class: 'mem-btn-row' }, [el.status, MEM.button('Esci', { href: CFG.logoutUrl, icon: 'log-out' })])
			]),
			h('main', { class: 'mem-wp__main' }, [el.panel, el.unavailable])
		]);
		setStatus(false, 'Connessione…');
	}

	var online = false;
	function setStatus(isOnline, text) {
		online = isOnline;
		el.status.className = 'mem-wp__status ' + (isOnline ? 'is-online' : 'is-offline');
		MEM.render(el.status, [MEM.icon(isOnline ? 'wifi' : 'wifi-off'), h('span', { text: text || (isOnline ? 'Connesso' : 'Non connesso') })]);
	}

	function now() { return Date.now() + offset; }

	function fetchChallenge() {
		if (fetching) { return; }
		fetching = true;
		var t0 = Date.now();
		MEM.api('workplace/challenge', { timeout: 8000 }).then(function (c) {
			var rtt = Date.now() - t0;
			offset = c.server_time * 1000 + rtt / 2 - Date.now();
			if (c.nonce) { CFG.nonce = c.nonce; }
			lastOk = Date.now();
			current = c;
			show(c);
			setStatus(true);
		}, function (err) {
			setStatus(false, err.status === 0 ? 'Non connesso' : 'Errore');
			if (err.status === 401 || err.status === 403) {
				MEM.render(el.unavailable.firstChild, [MEM.icon('log-in'), h('h1', { class: 'mem-wp__name', text: 'Sessione scaduta' }), h('p', { class: 'mem-wp__help', text: err.message }), MEM.button('Accedi di nuovo', { href: CFG.logoutUrl, variant: 'primary', icon: 'log-in' })]);
			}
			if (!current || current.expires_at <= now() / 1000) { unavailable(); }
			clearTimeout(retryTimer);
			retryTimer = setTimeout(fetchChallenge, 3000);
		}).finally(function () { fetching = false; });
	}

	function show(c) {
		el.name.textContent = c.workplace.name;
		el.pin.textContent = c.pin.slice(0, 3) + ' ' + c.pin.slice(3);
		el.pin.setAttribute('aria-label', 'PIN ' + c.pin.split('').join(' '));
		// SVG markup generated by the qrcode-generator library from our own URL.
		var qr = window.qrcode(0, 'M');
		qr.addData(c.qr_payload);
		qr.make();
		el.qr.innerHTML = qr.createSvgTag({ cellSize: 8, margin: 2, scalable: true, alt: 'Codice QR presenze ' + c.workplace.name });
		el.panel.hidden = false;
		el.unavailable.hidden = true;
	}

	function unavailable() {
		el.panel.hidden = true;
		el.unavailable.hidden = false;
		MEM.icons();
	}

	function loop() {
		if (current) {
			var left = current.expires_at - now() / 1000;
			if (left <= 0) {
				// Expired: never show a stale code.
				if (left < -2) { unavailable(); }
				fetchChallenge();
			} else {
				var pct = Math.max(0, Math.min(100, left / current.period * 100));
				el.fill.style.width = pct + '%';
				el.fill.parentNode.setAttribute('aria-valuenow', Math.ceil(left));
				el.secs.textContent = 'Nuovo codice tra ' + Math.ceil(left) + ' s';
			}
		}
		if (lastOk && online && Date.now() - lastOk > 20000) { setStatus(false); }
		window.requestAnimationFrame(function () { setTimeout(loop, 250); });
	}

	function keepAwake() {
		if (!('wakeLock' in navigator)) { return; }
		navigator.wakeLock.request('screen').then(function (l) { wakeLock = l; }, function () {});
	}

	build();
	fetchChallenge();
	loop();
	keepAwake();
	document.addEventListener('visibilitychange', function () {
		if (!document.hidden) { fetchChallenge(); keepAwake(); }
	});
	window.addEventListener('online', fetchChallenge);
	window.addEventListener('offline', function () { setStatus(false); });
})(window, document);
